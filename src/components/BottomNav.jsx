/**
 * Bottom tab bar - the main way users move between screens.
 * Uses plain buttons instead of a router library to keep the project
 * simple for beginners.
 */

const TABS = [
  { id: 'home', label: 'Home', icon: HomeIcon },
  { id: 'servers', label: 'Servers', icon: GlobeIcon },
  { id: 'settings', label: 'Settings', icon: GearIcon },
  { id: 'account', label: 'Account', icon: UserIcon },
]

export default function BottomNav({ current, onSelect }) {
  return (
    <nav className="bottom-nav" aria-label="Main navigation">
      {TABS.map((tab) => {
        const Icon = tab.icon
        const isActive = current === tab.id
        return (
          <button
            key={tab.id}
            type="button"
            className={`nav-item ${isActive ? 'nav-item--active' : ''}`}
            onClick={() => onSelect(tab.id)}
            aria-current={isActive ? 'page' : undefined}
          >
            <Icon />
            <span>{tab.label}</span>
          </button>
        )
      })}
    </nav>
  )
}

function HomeIcon() {
  return (
    <svg viewBox="0 0 24 24" width="22" height="22" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round" aria-hidden="true">
      <path d="M3 10.5 12 3l9 7.5" />
      <path d="M5 9.5V21h14V9.5" />
    </svg>
  )
}

